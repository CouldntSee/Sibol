
"""
SIBOL — train a CART tree and export it in the firmware's flat float format.

Usage:
    python train_model.py                 # uses seed_demo.csv
    python train_model.py captures.csv    # uses your own Teach export

Outputs (same folder):
    sibol_model.h     drop-in C array for SIBOL_NODE.ino
    params.json       node parameters matching the prototype build
    model_report.txt  metrics, confusion matrix, readable rules
"""
import sys, json
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeClassifier
from sklearn.model_selection import train_test_split
from sklearn.metrics import confusion_matrix, accuracy_score

HERE = Path(__file__).resolve().parent
FEATURES = ["soil_pct", "mq_mv"]          # order MUST match firmware x[0], x[1]
CLASSES = {0: "A SARIWA", 1: "B ALAGA", 2: "C PIGIL"}
MAX_DEPTH = 3
MIN_LEAF = 2
SEED = 42

PARAMS = dict(dry=2600, wet=1100, gain=1.0, avg=16, med=3, ema=0.28,
              vote=5, period=1000, warm=60, rl=1000, mq_vcc=3300)


def flatten(tree):
    """Preorder flatten -> [leaf, feature, threshold, left, right, class]."""
    rows = []

    def walk(node):
        i = len(rows)
        rows.append([0, 0, 0, 0, 0, 0])
        if tree.children_left[node] == -1:
            cls = int(np.argmax(tree.value[node][0]))
            rows[i] = [1, 0, 0, 0, 0, cls]
        else:
            rows[i] = [0, int(tree.feature[node]), float(tree.threshold[node]), 0, 0, 0]
            left = walk(tree.children_left[node])
            right = walk(tree.children_right[node])
            rows[i][3] = left
            rows[i][4] = right
        return i

    walk(0)
    return rows


def rules(rows, i=0, depth=0):
    n = rows[i]
    pad = "  " * depth
    if n[0] == 1:
        return f"{pad}-> {CLASSES[int(n[5])]}\n"
    feat = FEATURES[int(n[1])]
    out = f"{pad}if {feat} <= {n[2]:.2f}\n"
    out += rules(rows, int(n[3]), depth + 1)
    out += f"{pad}else\n"
    out += rules(rows, int(n[4]), depth + 1)
    return out


def main():
    src = HERE / (sys.argv[1] if len(sys.argv) > 1 else "seed_demo.csv")
    if not src.exists():
        sys.exit(f"missing data file: {src}")

    df = pd.read_csv(src)
    for col in FEATURES + ["label"]:
        if col not in df.columns:
            sys.exit(f"column '{col}' missing from {src.name}")

    tags = sorted(df["source"].unique()) if "source" in df.columns else ["untagged"]
    X = df[FEATURES].to_numpy(dtype=float)
    y = df["label"].to_numpy(dtype=int)

    print(f"data      : {src.name}  rows={len(df)}  source={','.join(map(str,tags))}")
    print("classes   : " + "  ".join(f"{CLASSES[k]}={int((y==k).sum())}" for k in sorted(CLASSES)))
    if "sim" in tags:
        print("NOTE      : synthetic demo rows. Metrics validate the pipeline, not field accuracy.")

    # ---- evaluate on a stratified hold-out ----
    Xtr, Xte, ytr, yte = train_test_split(
        X, y, test_size=0.3, stratify=y, random_state=SEED
    )
    probe = DecisionTreeClassifier(
        max_depth=MAX_DEPTH, min_samples_leaf=MIN_LEAF, random_state=SEED
    ).fit(Xtr, ytr)
    pred = probe.predict(Xte)
    acc = accuracy_score(yte, pred)
    cm = confusion_matrix(yte, pred, labels=[0, 1, 2])
    print(f"hold-out  : {len(yte)} rows  accuracy={acc:.3f}")
    print("confusion (rows=truth, cols=pred):")
    print(cm)

    # ---- refit on everything for the deployed tree ----
    final = DecisionTreeClassifier(
        max_depth=MAX_DEPTH, min_samples_leaf=MIN_LEAF, random_state=SEED
    ).fit(X, y)
    flat = flatten(final.tree_)
    nbytes = len(flat) * 6 * 4

    # ---- C header ----
    body = ",\n".join("  {" + ", ".join(f"{v:.2f}" for v in r) + "}" for r in flat)
    header = f"""/* SIBOL trained CART — generated by train_model.py
   data: {src.name}   source tag: {','.join(map(str,tags))}
   x[0]=soil_pct  x[1]=mq_mv   class 0=A 1=B 2=C
   {len(flat)} nodes, {nbytes} bytes */
#ifndef SIBOL_MODEL_H
#define SIBOL_MODEL_H

#define TREE_NODES {len(flat)}
static const float MODEL[TREE_NODES][6] = {{
{body}
}};

static inline int sibol_predict(const float *x) {{
  int i = 0, guard = 0;
  while (MODEL[i][0] == 0.0f && guard++ < TREE_NODES)
    i = (x[(int)MODEL[i][1]] <= MODEL[i][2]) ? (int)MODEL[i][3] : (int)MODEL[i][4];
  return (int)MODEL[i][5];
}}
#endif
"""
    (HERE / "sibol_model.h").write_text(header, encoding="utf-8")
    (HERE / "params.json").write_text(json.dumps(PARAMS, indent=2), encoding="utf-8")

    report = [
        f"data file      : {src.name}",
        f"source tag     : {','.join(map(str,tags))}",
        f"rows           : {len(df)}",
        f"features       : {FEATURES}",
        f"max_depth      : {MAX_DEPTH}",
        f"min_samples_leaf: {MIN_LEAF}",
        f"random_state   : {SEED}",
        f"hold-out rows  : {len(yte)}",
        f"hold-out acc   : {acc:.3f}",
        "confusion matrix (rows=truth, cols=pred):",
        str(cm),
        f"deployed nodes : {len(flat)}",
        f"flash bytes    : {nbytes}",
        "",
        "readable rules:",
        rules(flat),
    ]
    if "sim" in tags:
        report.insert(0, "SYNTHETIC DEMO DATA — not field measurements.")
    (HERE / "model_report.txt").write_text("\n".join(report), encoding="utf-8")

    print(f"exported  : sibol_model.h  params.json  model_report.txt")
    print(f"tree      : {len(flat)} nodes, {nbytes} bytes")
    print(rules(flat))


if __name__ == "__main__":
    main()